def create_docx(doc_info, output_dir):
    doc = docx.Document()
    
    # Page margins
    for section in doc.sections:
        section.top_margin = Inches(0.8)
        section.bottom_margin = Inches(0.8)
        section.left_margin = Inches(0.8)
        section.right_margin = Inches(0.8)
        
    # Header
    header = doc.add_paragraph()
    header.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    run_h = header.add_run("ООО «Фотопринт» · Внутренний нормативный документ\nСистема менеджмента качества ISO 9001:2026")
    run_h.font.size = Pt(8.5)
    run_h.font.color.rgb = RGBColor(120, 120, 120)

    # Title
    p_title = doc.add_paragraph()
    p_title.paragraph_format.space_before = Pt(12)
    p_title.paragraph_format.space_after = Pt(8)
    run_title = p_title.add_run(doc_info["title"])
    run_title.font.size = Pt(16)
    run_title.font.bold = True
    run_title.font.color.rgb = RGBColor(20, 40, 80)

    # Metadata Table
    table = doc.add_table(rows=4, cols=2)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = False
    
    metadata = [
        ("Идентификатор регламента:", doc_info["id"]),
        ("Категория документа:", doc_info["category"]),
        ("Дата утверждения / редакция:", doc_info["date"]),
        ("Уровень доступа (RBAC):", f"{doc_info['clearance_str']} (Clearance: {doc_info['clearance']})")
    ]
    
    for row_idx, (k, v) in enumerate(metadata):
        row = table.rows[row_idx]
        cell_0 = row.cells[0]
        cell_1 = row.cells[1]
        
        cell_0.width = Inches(2.2)
        cell_1.width = Inches(4.5)
        
        p0 = cell_0.paragraphs[0]
        p0.paragraph_format.space_after = Pt(2)
        r0 = p0.add_run(k)
        r0.font.bold = True
        r0.font.size = Pt(9.5)
        r0.font.color.rgb = RGBColor(80, 80, 80)
        
        p1 = cell_1.paragraphs[0]
        p1.paragraph_format.space_after = Pt(2)
        r1 = p1.add_run(v)
        r1.font.size = Pt(9.5)
        if "Уровень 1" in v:
            r1.font.bold = True
            r1.font.color.rgb = RGBColor(180, 20, 20)
        elif "Уровень 2" in v:
            r1.font.bold = True
            r1.font.color.rgb = RGBColor(30, 100, 180)
        else:
            r1.font.color.rgb = RGBColor(30, 120, 40)

    doc.add_paragraph().paragraph_format.space_after = Pt(8)

    # Summary box
    p_sum_head = doc.add_paragraph()
    r_sum_head = p_sum_head.add_run("АННОТАЦИЯ И КЛЮЧЕВЫЕ ПОЛОЖЕНИЯ")
    r_sum_head.font.bold = True
    r_sum_head.font.size = Pt(11)
    r_sum_head.font.color.rgb = RGBColor(30, 50, 90)

    p_sum = doc.add_paragraph()
    p_sum.paragraph_format.left_indent = Inches(0.2)
    p_sum.paragraph_format.space_after = Pt(14)
    r_sum = p_sum.add_run(doc_info["summary"])
    r_sum.font.italic = True
    r_sum.font.size = Pt(10)

    # Full text
    p_body_head = doc.add_paragraph()
    r_body_head = p_body_head.add_run("ТЕКСТ РЕГЛАМЕНТА")
    r_body_head.font.bold = True
    r_body_head.font.size = Pt(11)
    r_body_head.font.color.rgb = RGBColor(30, 50, 90)

    for para_text in doc_info["content"].split("\n\n"):
        p = doc.add_paragraph()
        p.paragraph_format.space_after = Pt(6)
        p.paragraph_format.line_spacing = 1.15
        
        # Check if section title
        if para_text.strip().startswith(("1.", "2.", "3.", "КОНФИДЕНЦИАЛЬНО")):
            r = p.add_run(para_text.strip())
            r.font.bold = True
            r.font.size = Pt(10.5)
            r.font.color.rgb = RGBColor(40, 40, 40)
        else:
            r = p.add_run(para_text.strip())
            r.font.size = Pt(10)
            r.font.color.rgb = RGBColor(20, 20, 20)

    # Footer
    p_foot = doc.add_paragraph()
    p_foot.paragraph_format.space_before = Pt(20)
    r_foot = p_foot.add_run(f"Документ зарегистрирован в корпоративном реестре ООО «Фотопринт». ID: {doc_info['id']}. Контур: On-Premise.")
    r_foot.font.size = Pt(8)
    r_foot.font.color.rgb = RGBColor(140, 140, 140)

    # Save filename
    clean_title = doc_info["title"].replace(" ", "_").replace("«", "").replace("»", "").replace(":", "").replace('"', "")[:45]
    filename = f"{doc_info['id']}_{clean_title}.docx"
    filepath = os.path.join(output_dir, filename)
    doc.save(filepath)
    return filepath

