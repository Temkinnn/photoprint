import json
import sys
from openai import OpenAI

# Подключаемся к локальной Ollama
client = OpenAI(
    base_url="http://localhost:11434/v1",
    api_key="ollama"
)

# Пробуем основную модель 7b, если нет — используем легкую 0.5b
MODEL_NAME = "qwen2.5:7b"

# Реалистичная стенограмма планерки ООО «Фотопринт» для тестирования
SAMPLE_TRANSCRIPT = """
[00:01] Директор (Смирнов): Коллеги, доброе утро. На повестке запуск новой линейки фотоальбомов 20х20.
[00:15] Иванов (Нач. производства): Станки готовы, но нужно перенастроить линию УФ-лакировки под этот формат. Я сделаю это до пятницы, 15 ноября.
[00:32] Директор: Отлично, фиксируем. Что с закупкой матовой бумаги 200 грамм?
[00:45] Петрова (Снабжение): Поставщик просит предоплату 50%, а у нас по регламенту лимит 30%. Я пока не согласовала договор.
[01:05] Директор: По регламенту нарушать нельзя, проведи повторные переговоры до четверга.
[01:20] Иванов: Еще один момент — если объем заказов вырастет вдвое, у нас возникнет дефицит людей в ночную смену на резке. Нужно открывать вакансию.
[01:40] Директор: Вопрос с ночной сменой пока подвесим, обсудим в следующий понедельник, когда маркетинг покажет прогноз.
"""

def test_extract_meeting_minutes():
    print(f"[*] Отправляем стенограмму в модель '{MODEL_NAME}' через Ollama...")
    
    system_prompt = """
    Ты — аналитический AI-ассистент руководителя ООО «Фотопринт».
    Твоя задача — проанализировать расшифровку встречи и выделить:
    
    1. decisions (Принятые решения):
       - type: "resolved" (утверждено) или "needs_clarification" (требует уточнения / не решено)
       - text: формулировка решения
       
    2. tasks (Задачи / Action Items):
       - temp_id: порядковый номер (t1, t2...)
       - title: четкая формулировка задачи
       - assignee_name: ФИО и должность (если не назван — напиши "требует уточнения")
       - deadline: дата/срок (если не назван — напиши "требует уточнения")
       - source_quote: точная цитата из стенограммы
       - timestamp: таймкод фразы
       - status: "pending_approval" (все задачи создаются как черновики для подтверждения директором)
       
    3. identified_risks (Обнаруженные риски и предупреждения):
       - риск и на что он влияет
       
    4. open_questions (Открытые нерешенные вопросы на следующую встречу).

    Ответ верни СТРОГО в виде валидного JSON-объекта со структурой:
    {
      "decisions": [...],
      "tasks": [...],
      "identified_risks": [...],
      "open_questions": [...]
    }
    Никакого лишнего текста до и после JSON.
    """

    try:
        response = client.chat.completions.create(
            model=MODEL_NAME,
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": f"Стенограмма встречи:\n{SAMPLE_TRANSCRIPT}"}
            ],
            temperature=0.1,
            response_format={"type": "json_object"}
        )
        
        result_text = response.choices[0].message.content
        parsed = json.loads(result_text)
        
        print("\n" + "="*50)
        print("  РЕЗУЛЬТАТ АНАЛИЗА ВСТРЕЧИ (СТАТУС: УСПЕШНО)")
        print("="*50)
        print(json.dumps(parsed, indent=2, ensure_ascii=False))
        print("="*50)
        return parsed
        
    except Exception as e:
        print(f"\n[!] Ошибка при обращении к модели: {e}")
        print("Подсказка: убедитесь, что Ollama запущена командой 'ollama serve' или приложением в трее.")

if __name__ == "__main__":
    test_extract_meeting_minutes()
